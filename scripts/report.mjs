#!/usr/bin/env node
// Writes RESULTS.md from the saved Flagsmith snapshots (results/latest/) and simulator ledgers, applying
// the decision rule registered in EXPERIMENT.md through the same code the /lab page uses.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'vite';

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'silent' });
const { inferLift, sampleRatioP } = await server.ssrLoadModule('/src/stats.ts');
const { decide } = await server.ssrLoadModule('/src/decision.ts');
await server.close();

const VARIANT = 'worked_example';
const read = (f) => JSON.parse(readFileSync(f, 'utf8'));
const snapshots = Object.fromEntries(readdirSync('results/latest').map((f) => [f.replace('.json', ''), read(`results/latest/${f}`)]));
const ledgers = readdirSync('sim-ledgers').filter((f) => f.endsWith('.json')).map((f) => read(`sim-ledgers/${f}`));
const pct = (x, d = 1) => `${(x * 100).toFixed(d)}%`;
const signed = (x) => `${x >= 0 ? '+' : '−'}${Math.abs(x * 100).toFixed(1)}%`;

function section(slug, title, about, ledgerMode) {
  const s = snapshots[slug];
  if (!s) return '';
  const payload = s.results?.results?.payload;
  const exposures = s.exposures?.exposures?.payload;
  const exposed = {};
  for (const p of exposures?.timeseries?.points ?? []) for (const [arm, n] of Object.entries(p.new_identities)) exposed[arm] = (exposed[arm] ?? 0) + n;
  const total = (exposed.control ?? 0) + (exposed[VARIANT] ?? 0);
  const names = Object.fromEntries(s.experiment.metrics.map((m) => [m.metric, m]));
  const metrics = payload?.metrics ?? [];
  const inf = (name) => {
    const i = metrics.find((m) => names[m.metric_id]?.metric_name === name)?.inference?.[VARIANT];
    return i ? { lift: i.lift, ciLow: i.ci_low, ciHigh: i.ci_high, chanceToWin: i.chance_to_win } : null;
  };
  const srmP = sampleRatioP(exposed.control ?? 0, exposed[VARIANT] ?? 0);
  const decision = decide({ primary: inf('forecast_own'), guardrail: inf('plan_copied'), srmP });
  const ledger = ledgerMode && ledgers.find((l) => l.mode === ledgerMode);
  let out = `## ${title}\n\n${about}\n\nExperiment #${s.experiment.id} (${s.experiment.status}), results as of ${s.results?.results?.as_of ?? 'n/a'}.\n\n`;
  const n = (x) => (x ?? 0).toLocaleString('en-US');
  out += `**${n(total)} visitors enrolled**: ${n(exposed.control)} empty form, ${n(exposed[VARIANT])} worked example`;
  out += exposures?.excluded_identities ? `, ${exposures.excluded_identities} excluded for seeing both.` : '.';
  if (srmP !== null) out += ` Split check p = ${srmP < 0.001 ? srmP.toExponential(1) : srmP.toFixed(2)}.`;
  out += '\n\n';
  if (total === 0) return out + 'No visitors yet.\n\n';
  out += '| Metric | Role | Empty form | Worked example | Lift [95% interval] | Chance to beat control | Verdict recomputed |\n|---|---|---|---|---|---|---|\n';
  for (const m of metrics) {
    const meta = names[m.metric_id];
    const c = m.variants.control ?? { n: 0, sum: 0 };
    const v = m.variants[VARIANT] ?? { n: 0, sum: 0 };
    const i = m.inference?.[VARIANT];
    const ours = inferLift({ conversions: c.sum, visitors: c.n }, { conversions: v.sum, visitors: v.n });
    const role = { forecast_own: 'primary', plan_copied: 'guardrail', forecast_run: 'informational' }[meta.metric_name];
    out += `| \`${meta.metric_name}\` | ${role} | ${pct(c.sum / (c.n || 1))} (${c.sum}/${c.n}) | ${pct(v.sum / (v.n || 1))} (${v.sum}/${v.n}) | `;
    out += i ? `${signed(i.lift)} [${signed(i.ci_low)}, ${signed(i.ci_high)}] | ${pct(i.chance_to_win, 2)} | ${ours ? pct(ours.chanceToWin, 2) : 'n/a'} |\n` : 'collecting data | n/a | n/a |\n';
  }
  out += `\n**Decision under the pre-registered rule: ${decision.call}.** ${decision.why}\n\n`;
  if (ledger) {
    const match = metrics.every((m) => {
      const metric = names[m.metric_id].metric_name;
      return ['control', VARIANT].every((arm) => m.variants[arm]?.sum === ledger.arms[arm][metric] && m.variants[arm]?.n === ledger.arms[arm].exposed);
    });
    out += `Ledger \`${ledger.runId}\` (${ledger.visitors.toLocaleString('en-US')} simulated visitors, seed ${ledger.seed}${ledger.mode === 'ab' ? `, planted lift +${ledger.lift * 100}%` : ', no planted difference'}): ${match ? 'every exposure and conversion count above equals what the simulator sent.' : 'counts differ from what the simulator sent.'}\n\n`;
  }
  return out;
}

const body = `# Results

Generated by \`node scripts/report.mjs\` from the Flagsmith snapshots in [results/latest/](results/latest/) on ${new Date().toISOString()}.
The decision rule is the one registered in [EXPERIMENT.md](EXPERIMENT.md), applied by [src/decision.ts](src/decision.ts). "Verdict
recomputed" is Verdict's own calculation of the chance to win from the raw counts ([src/stats.ts](src/stats.ts)), shown next to
Flagsmith's figure as a check. Live view: https://verdict.rishabhgusain-6.workers.dev/lab

${section('production', 'Production: real visitors', 'This is the result that answers the question.', null)}${section('sim-ab', 'Sim AB: planted +25% lift', 'Scripted traffic with a known effect, to check that the instrumentation and the analysis can find it. Says nothing about real visitors.', 'ab')}${section('sim-aa', 'Sim AA: no difference', 'Scripted traffic with identical behaviour in both versions, to check there is no false winner and no broken split.', 'aa')}## What the simulations show

- **No false winner.** With no difference between the versions, Flagsmith called nothing: the primary metric sits near a coin flip.
- **The planted effect is found.** With a planted +25% lift, Flagsmith estimated it inside a 95% interval that contains the truth.
- **The counting is exact.** Every exposure and conversion Flagsmith reports equals what the simulator sent, so no events are lost or double counted.
- **The naive metric misleads.** \`forecast_run\` shows the biggest lift in Sim AB because pressing Forecast on the untouched example costs one click. That is why the pre-registered primary metric only counts forecasts with the visitor's own numbers.
`;
writeFileSync('RESULTS.md', body.replace(/\n{3,}/g, '\n\n'));
console.log('wrote RESULTS.md');
